# ══════════════════════════════════════════════════════════
# 部分 1：读 PDF
# ══════════════════════════════════════════════════════════

def 读PDF(路径):                                    # 定义函数：读 PDF
    """把 PDF 每一页的文字抽出来，拼成一个大字符串。

    参数：路径 —— PDF 文件的位置
    返回：整本书的文字（一个很长的 str）

    注意：PDF 里如果是「图片扫描件」，抽出来是空的。
          能抽出来字的 PDF 叫「文字版 PDF」。
    """
    阅读器 = PdfReader(str(路径))        # 打开 PDF，拿到一个「阅读器」对象
    所有页的文字 = []                    # 空列表，准备一页一页往里放
    for 第几页 in range(len(阅读器.pages)):       # 逐页遍历：第 0 页、第 1 页……
        一页 = 阅读器.pages[第几页]      # 取出第「第几页」页
        文字 = 一页.extract_text() or "" # 抽这一页的文字；抽不到就给空字符串
        所有页的文字.append(文字)        # 把这一页的文字放进列表
    return "\n".join(所有页的文字)       # 用换行把每一页接起来，变成一整段


def 读TXT(路径):                                    # 定义函数：读 TXT
    """读一个纯文本文件，整个返回。

    参数：路径 —— txt 文件的位置
    返回：文件的全部文字
    """
    return Path(路径).read_text(encoding="utf-8")   # 按 UTF-8 读，中文才不会乱码


# ══════════════════════════════════════════════════════════
# 部分 2：固定字数切（最简单，但会切断句子）
# ══════════════════════════════════════════════════════════

def 固定字数切(文本, 每段字数=500):                  # 定义函数：按固定字数切
    """每隔「每段字数」个字切一刀，不管切在哪儿。

    参数：文本     —— 一整篇文字
        每段字数 —— 每段大概多长（默认 500）
    返回：一个列表，每个元素是一段文字
    """
    段落列表 = []                                   # 结果放这里
    # range(0, 总长, 步长) 会产生 0, 500, 1000, 1500 ... 这些起始位置
    for 起点 in range(0, len(文本), 每段字数):       # 起点按步长递增
        一段 = 文本[起点 : 起点 + 每段字数]          # 从起点往后取 500 个字
        段落列表.append(一段)                        # 放进结果
    return 段落列表                                  # 交出所有段


# ══════════════════════════════════════════════════════════
# 部分 3：按段落切 + 相邻重叠（真实项目里的做法）
# ══════════════════════════════════════════════════════════

def 按段落切(文本, 每段字数=500, 重叠=50):          # 定义函数：按段落切 + 重叠
    """先按行拆开，再往上「装」，装到装不下就封一包，并把上一包的尾巴带过来。

    参数：文本     —— 一整篇文字
        每段字数 —— 每包最多装多少字（默认 500）
        重叠     —— 新的一包开头，带上上一包末尾多少字（默认 50）
    返回：一个列表，每个元素是一段文字

    为什么要重叠：
        一句话正好被切开时，前半句在上一包、后半句在下一包，
        检索到任何一包都只拿到半句。让相邻两包重叠 50 字，
        切在边界上的那句话，至少有一包是完整的。
    """
    # 把全文按换行拆成一行一行，去掉空行（空行没有信息，只会占位置）
    行们 = [行.strip() for 行 in 文本.split("\n") if 行.strip()]   # 拆行 + 去空行

    段落列表 = []      # 切好的包
    当前 = ""          # 正在装的那一包

    for 行 in 行们:                                  # 一行一行地装
        # 这一行还装得下吗？+1 是给换行符留的位置
        if len(当前) + len(行) + 1 <= 每段字数:      # 装得下
            当前 = 当前 + 行 + "\n"                  # 就把这一行接到当前包末尾
        else:                                        # 装不下
            段落列表.append(当前)                    # 先把当前这包封口，放进结果
            # 取上一包的「尾巴」：最后 50 个字。
            # 当前[-50:] 的意思是「从倒数第 50 个字符取到最后」
            尾巴 = 当前[-重叠:] if 重叠 > 0 else ""  # 取上一包末尾的「重叠」个字
            当前 = 尾巴 + 行 + "\n"                  # 新的一包：先用上一包的尾巴开头，再装这一行

    if 当前.strip():                                 # 循环结束后，最后一包还没封口
        段落列表.append(当前)                        # 把最后一包也放进结果

    return 段落列表                                  # 交出所有包


# ══════════════════════════════════════════════════════════
# 小工具：把结果打印得好看一点
# ══════════════════════════════════════════════════════════

def 报告(名称, 段落列表):                          # 定义函数：打印切分统计
    """打印「切成了几段、平均多长、最长最短各多少」。"""
    长度们 = [len(x) for x in 段落列表]              # 每段的字数
    平均 = sum(长度们) / len(长度们)                 # 平均长度
    print(f"  {名称}：{len(段落列表)} 段  "           # 打印：名称、段数
          f"平均 {平均:.0f} 字  "                     # 打印：平均字数
          f"最短 {min(长度们)} 字  最长 {max(长度们)} 字")   # 打印：最短、最长


def 看几段(段落列表, 几段=2, 前多少字=80):          # 定义函数：打印前几段的开头
    """把前几段的开头打印出来，让你亲眼看到切成了什么样。"""
    for i in range(min(几段, len(段落列表))):         # 只打印前「几段」段
        开头 = 段落列表[i][:前多少字].replace("\n", " ")   # 取开头、换行换成空格，方便一行显示
        print(f"  第{i}段（{len(段落列表[i])}字）：{开头}…")   # 打印：第几段、字数、开头


