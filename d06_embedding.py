句子 = [
    "今天天气很好",
    "今儿个天气不错",
    "我喜欢吃火锅",
    "检索增强生成能减少幻觉",
]


def 演示2_真实向量():
    """把 4 句话变成 512 维向量，并两两算相似度。"""
    print("=" * 62)
    print("第二部分：真实 Embedding（512 维）")
    print("=" * 62)

    # 转向量 返回一个 (句子数, 512) 的矩阵
    向量 = 转向量(句子)

    print("每句话 →", len(向量[0]), "个数字")
    for s, v in zip(句子, 向量):
        # v[:5] 只取前 5 个数字；round(...,3) 保留 3 位小数
        前五个 = [round(float(x), 3) for x in v[:5]]
        print(f"  {s:12s} {前五个}")
    print()

    print("两两相似度（1 = 完全一样，0 = 毫无关系）：")
    for i in range(len(句子)):
        # 内层从 i+1 开始：每对只算一次，也不会自己跟自己比
        for j in range(i + 1, len(句子)):
            s = 余弦相似度(向量[i], 向量[j])
            print(f"  {句子[i]:12s} ↔ {句子[j]:12s}  {s:.4f}")
    print()
    print("关键：『今天天气很好』↔『今儿个天气不错』字面几乎不同，但相似度 0.84")
    print("      说明模型比的是【意思】，不是字面。")
    print()


