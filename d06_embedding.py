def 点积(a, b):
    """两个向量对应位置相乘，再把所有乘积加起来。

    例子：[1, 2] 和 [3, 4] → 1*3 + 2*4 = 11
    """
    结果 = 0                       # 累加器：从 0 开始，装总和
    for x, y in zip(a, b):         # zip 把 a 和 b 并排拉在一起，一次取一对
        结果 = 结果 + x * y        # 这一对相乘，加进累加器
    return 结果                     # 循环结束，交出总和


def 长度(v):
    """向量长度 = 各分量平方和再开根号（勾股定理的推广）。

    例子：[3, 4] → √(9 + 16) = √25 = 5
    """
    平方和 = 0                      # 累加器
    for x in v:                     # 遍历每个分量
        平方和 = 平方和 + x * x     # 平方后加进去
    return math.sqrt(平方和)        # 开根号


def 余弦相似度_手写(a, b):
    """余弦相似度 = 点积 ÷ (长度a × 长度b)。

    结果范围：
        1  = 方向相同（完全一样）
        0  = 垂直（毫无关系）
        -1 = 方向相反（意思相反）
    """
    return 点积(a, b) / (长度(a) * 长度(b))


def 演示1_手写余弦相似度():
    """用 2 维向量跑四种情况，看清公式在干嘛。"""
    print("=" * 62)
    print("第一部分：手写余弦相似度（2 维向量）")
    print("=" * 62)

    print("情况 1：方向相同  a=[1,0]  b=[2,0]")
    print("        相似度 =", round(余弦相似度_手写([1, 0], [2, 0]), 4), "  ← 1.0")
    print()

    print("情况 2：互相垂直  a=[1,0]  b=[0,3]")
