    print()

    print("情况 3：方向相反  a=[1,2]  b=[-1,-2]")
    print("        相似度 =", round(余弦相似度_手写([1, 2], [-1, -2]), 4), "  ← -1")
    print()

    print("情况 4：偏一点    a=[1,0]  b=[1,1]")
    print("        相似度 =", round(余弦相似度_手写([1, 0], [1, 1]), 4), "  ← 0.707")
    print()


