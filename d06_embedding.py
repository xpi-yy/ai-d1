文档库 = [
    "今天天气很好，适合出门散步",
    "RAG 的核心是先检索再生成",
    "火锅是四川的特色美食",
    "检索增强生成可以减少模型幻觉",
    "明天可能下雨，记得带伞",
    "向量数据库用来做相似度搜索",
    "张三是公司的销售经理",
    "FAISS 是 Facebook 开源的向量检索库",
]


def 演示3_faiss检索():
    """用 FAISS 建索引，输入问题返回最相关的 3 段。"""
    import faiss   # 放在函数里 import，这样不跑这个演示时不加载

    print("=" * 62)
    print("第三部分：FAISS 向量检索")
    print("=" * 62)

    # ① 所有文档变向量
    #    .numpy()            torch 张量 → numpy 数组
    #    .astype("float32")  FAISS 要求 float32
    文档向量 = 转向量(文档库).numpy().astype("float32")
    print("文档向量形状:", 文档向量.shape, " 读作（文档数, 维度）")

    # ② 建索引。IndexFlatL2 = 暴力逐一比较，小数据够用
    索引 = faiss.IndexFlatL2(文档向量.shape[1])   # 参数是向量维度 512
    索引.add(文档向量)                            # 把 8 个向量加进去
    print("索引里的向量数量:", 索引.ntotal)

    # ③ 搜索
    问题 = "怎么减少大模型的幻觉？"
    # 注意：外面套 [问题]，因为 FAISS 要 (查询数, 维度) 的二维数组
    问题向量 = 转向量([问题]).numpy().astype("float32")

    # search 返回两个数组：距离（越小越像）和编号（对应文档库的下标）
    距离, 编号 = 索引.search(问题向量, 3)

    print(f"\n问题：{问题}")
    print("最相关的 3 段：")
    for k in range(3):
        # 编号[0][k]：[0] 是第 0 个查询（只有 1 个），[k] 是第 k 条结果
        idx = 编号[0][k]
        print(f"  {k + 1}. {文档库[idx]}")
    print()


# ══════════════════════════════════════════════════════════
# 第四部分：自己写检索函数（不依赖 FAISS）
# ══════════════════════════════════════════════════════════

def search(问题, 文档列表, k=3):
    """暴力版检索：给一个问题，返回最相关的 k 篇文档正文。

    参数：
        问题     —— 一句提问
        文档列表 —— 一堆候选文本
        k        —— 返回几条（默认 3）

    返回：
        最相关的 k 篇文档正文，组成一个列表
    """
    # ① 问题 → 一个 512 维向量
    #    转向量([问题]) 返回 (1, 512) 的矩阵，[0] 取出第一行
    问题向量 = 转向量([问题])[0]

    # ② 所有文档 → (篇数, 512) 的矩阵
    #    注意：这里不加 [i]，因为要的是【全部】文档
    文档向量 = 转向量(文档列表)

    # ③ 给每一篇打分，存成 (分数, 下标) 的小包裹
    打分的 = []
    for i in range(len(文档列表)):                  # i 从 0 到「篇数-1」
        # 文档向量[i] 是第 i 篇的向量（矩阵的第 i 行）
        分数 = 余弦相似度(问题向量, 文档向量[i])
        打分的.append((分数, i))                     # 打包：分数 + 下标
        # ↑ 必须存下标，否则排完序就不知道第 1 名是哪篇了

    # ④ 按分数从大到小排序
    #    注意：sorted 返回【新列表】，所以左边要接住
    #          这和 append 相反 —— append 是原地修改，不能接
    打分的 = sorted(打分的, key=lambda 对: 对[0], reverse=True)
    #                                  ↑ 按包裹的第 0 个元素（分数）比大小

    # ⑤ 取前 k 个，用下标换回正文
    结果 = []
    for 对 in 打分的[:k]:                            # [:k] 取前 k 个包裹
        结果.append(文档列表[对[1]])                  # 对[1] 是下标 → 取正文

    return 结果


def 演示4_自己写检索():
    """调用自己写的 search，和 FAISS 的结果对比。"""
    print("=" * 62)
    print("第四部分：自己写的暴力检索")
    print("=" * 62)

    问题 = "怎么减少大模型的幻觉？"
    结果 = search(问题, 文档库, 3)

    print(f"问题：{问题}")
    for i, d in enumerate(结果, 1):     # enumerate(…,1) 同时给序号（从 1 开始）和内容
        print(f"  {i}. {d}")
    print()

    # 断言：结果里必须有一条跟幻觉相关，且正好 3 条
    assert any("幻觉" in d for d in 结果), "最相关的里面应该出现幻觉相关的文档"
    assert len(结果) == 3
    print("D6 任务通过 ✅")
    print()


